// Night version of a day preset: moonlight, dark sky, stars, the bird lit like in the
// hand-tuned Sahara night; clouds kept but dark, no cumulus towers or distant birds.
function night(P) {
  const dim = (c, k) => c.map((x) => x * k);
  const overcast = P.clouds.some((c) => c.cov > 0.8 && c.opacity > 0.9);
  // dark ground (forest canopy, sea, conifers) would turn black under the same moon: brighter
  // moonlight there, so the land still reads and the horizon stays a silhouette
  const boost = { 3: 1.3, 5: 1.6, 6: 2.4, 10: 1.8, 12: 1.3 }[P.habitat] || 1;
  return {
    ...P, base: undefined, night: true,
    caption: P.caption.replace(/(, )?(late afternoon|autumn morning|late summer|low autumn sun|after the rains)/, '')
      .replace(/, ([\d ]+ m)$/, overcast ? ', at night, $1' : ', by moonlight, $1'),
    sun: { elev: P.habitat === 5 ? 14 : 28, az: P.habitat === 5 ? 170 : P.sun.az }, sunCol: dim([0.40, 0.44, 0.58], boost), amb: dim([0.035, 0.042, 0.065], Math.sqrt(boost)),
    zenith: [0.002, 0.0035, 0.009], horizon: [0.028, 0.034, 0.054], horizon2: [0.018, 0.023, 0.038], below: [0.6, 0.6, 0.6],
    glow: [0.02, 0.024, 0.035], glowPow: 10, sunDisc: 0, moon: overcast ? [0, 0, 0] : [1.3, 1.25, 1.15],
    waterCol: dim(P.waterCol || [0.02, 0.05, 0.07], 0.5), foam: (P.foam || 0) * 0.3, mist: (P.mist || 0) * 0.8,
    clouds: P.clouds.map((c) => ({ ...c, lit: dim(c.lit, 0.07), shade: dim(c.shade, 0.05), under: dim(c.under, 0.05) })),
    cloudShadow: 0, cumulus: null, flock: null,
    bird: { sun: 6.5, env: 7.0, fill: 2.2, rim: 2.8 }, exposure: 1.35, stars: overcast ? 0 : 1.1, milky: overcast ? 0 : 0.1, desat: 0.6,
    bloom: { strength: 0.25, radius: 0.5, threshold: 1.2 },
  };
}
